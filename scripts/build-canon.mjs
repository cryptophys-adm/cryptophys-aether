// Builds the Aether Canon bundle (src/canon.generated.mjs) from canon/*.json.
//   file hash    = sha256(raw file bytes)
//   content hash = sha256 of "<path>\t<file sha256>\n" for each canon file, in CANON_FILES order
// `node scripts/build-canon.mjs --write` regenerates the bundle; `--check` (CI and the tests) fails
// when the bundle is stale. The canon changes only by a reviewed PR.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const CANON_FILES = Object.freeze(["canon/doctrine.json", "canon/roles.json", "canon/definitions.json", "canon/indicator/kb-v4.json"]);
export const GENERATED_PATH = "src/canon.generated.mjs";
export const CANON_VERSION = "aether.canon.v1";

const sha256 = (data) => createHash("sha256").update(data).digest("hex");

export function buildCanon() {
  const files = CANON_FILES.map((p) => { const raw = readFileSync(path.join(ROOT, p)); return { path: p, sha256: sha256(raw), json: JSON.parse(raw.toString("utf8")) }; });
  const contentSha = sha256(files.map((f) => `${f.path}\t${f.sha256}\n`).join(""));
  const [doctrine, roles, definitions, kb] = files.map((f) => f.json);
  return {
    version: CANON_VERSION,
    content_sha256: contentSha,
    files: files.map(({ path: p, sha256: s }) => ({ path: p, sha256: s })),
    doctrine, roles, definitions,
    indicator: { kb_version: kb.version, kb_content_sha256: kb.provenance?.content_sha256 ?? null, kb }
  };
}

export function renderModule(canon = buildCanon()) {
  return "// GENERATED by scripts/build-canon.mjs --write. Do not edit by hand.\n" +
    `export const CANON = Object.freeze(${JSON.stringify(canon, null, 2)});\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = renderModule();
  const target = path.join(ROOT, GENERATED_PATH);
  if (process.argv.includes("--write")) { writeFileSync(target, out); console.log(`wrote ${GENERATED_PATH}`); }
  else if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(target, "utf8"); } catch { current = ""; }
    if (current !== out) { console.error(`stale: run node scripts/build-canon.mjs --write`); process.exit(1); }
    console.log("canon bundle is up to date");
  } else console.log(JSON.stringify({ version: CANON_VERSION, content_sha256: buildCanon().content_sha256 }, null, 2));
}
